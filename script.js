function applyLanguage(lang) {
  const dict = translations[lang];
  if (!dict) return;

  document.documentElement.setAttribute('lang', lang === 'pt' ? 'pt-BR' : 'en');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.getAttribute('data-i18n-attr').split(';').forEach((pair) => {
      const [attr, key] = pair.split(':');
      if (attr && key && dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    const isActive = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', isActive);
    btn.setAttribute('aria-pressed', String(isActive));
  });

  const footerText = document.getElementById('footer-text');
  if (footerText) footerText.textContent = dict.footer_text;

  try { localStorage.setItem('portfolio-lang', lang); } catch (e) { /* localStorage indisponível */ }
}

document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => applyLanguage(btn.getAttribute('data-lang')));
});

let initialLang = 'pt';
try {
  const saved = localStorage.getItem('portfolio-lang');
  if (saved === 'pt' || saved === 'en') {
    initialLang = saved;
  } else if (navigator.language && navigator.language.toLowerCase().startsWith('pt')) {
    initialLang = 'pt';
  } else if (navigator.language) {
    initialLang = 'en';
  }
} catch (e) { /* localStorage indisponível */ }

applyLanguage(initialLang);

